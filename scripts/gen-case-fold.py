"""Generate the case-fold table and its test vectors from Python's str.casefold().

Home Assistant compares registry names with casefold() (normalized_name_base_registry.py), so the card needs the
same mapping. Run with the Python that Home Assistant requires (3.14.2 or later for core 2026.11.2):

    uv run --python 3.14 python -I scripts/gen-case-fold.py

It writes src/domain/text/case-fold-table.ts and test/fixtures/synthetic/casefold-vectors.json.
"""

import datetime
import json
import pathlib
import sys
import unicodedata

ROOT = pathlib.Path(__file__).resolve().parent.parent
COMMAND = "uv run --python 3.14 python -I scripts/gen-case-fold.py"


def changed_code_points():
    for cp in range(sys.maxunicode + 1):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        folded = chr(cp).casefold()
        if folded != chr(cp):
            yield cp, folded


def single_ranges(singles):
    """Runs of code points with the same step (1 or 2) and the same delta: [start, end, step, delta]."""
    runs = []
    for cp, delta in singles:
        if runs:
            start, end, step, run_delta = runs[-1]
            gap = cp - end
            if run_delta == delta and ((start == end and gap in (1, 2)) or gap == step):
                runs[-1] = [start, cp, gap if start == end else step, delta]
                continue
        runs.append([cp, cp, 1, delta])
    return runs


def main():
    changed = list(changed_code_points())
    singles = [(cp, ord(f) - cp) for cp, f in changed if len(f) == 1]
    multis = [(cp, f) for cp, f in changed if len(f) > 1]
    runs = single_ranges(singles)
    header = {
        "python": sys.version.split()[0],
        "unidata": unicodedata.unidata_version,
        "date": datetime.date.today().isoformat(),
        "command": COMMAND,
    }
    ranges = ";".join(",".join(format(v, "x") for v in run) for run in runs)
    multi = ";".join(format(cp, "x") + ":" + ",".join(format(ord(c), "x") for c in f) for cp, f in multis)
    table = (
        "// GENERATED by scripts/gen-case-fold.py: do not edit.\n"
        f"// Python {header['python']}, unicodedata {header['unidata']}, {header['date']}.\n"
        f"// Command: {COMMAND}\n"
        "// Every code point that str.casefold() changes, in hexadecimal:\n"
        "// SINGLE_RANGES is `start,end,step,delta;…` (one code point to one), MULTI is `cp:out,out,…;…`.\n\n"
        f'export const SINGLE_RANGES = "{ranges}";\n\n'
        f'export const MULTI = "{multi}";\n'
    )
    (ROOT / "src/domain/text/case-fold-table.ts").write_text(table, encoding="utf-8", newline="\n")
    vectors = {**header, "vectors": [[cp, f] for cp, f in changed]}
    out = ROOT / "test/fixtures/synthetic/casefold-vectors.json"
    out.write_text(json.dumps(vectors, ensure_ascii=False, separators=(",", ":")) + "\n", encoding="utf-8", newline="\n")
    print(f"{len(changed)} code points, {len(runs)} single ranges, {len(multis)} multi")


if __name__ == "__main__":
    main()
